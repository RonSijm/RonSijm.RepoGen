    public static string Render(RepositoryGenerationModel model)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");

        AppendRepositoryInfrastructure(builder, model.Settings);

        if (model.Entities.Any(static entity => entity.GenerateSelectors))
        {
            AppendSelectorBases(builder, model.Settings);
        }

        foreach (var entity in model.Entities)
        {
            builder.AppendLine();
            if (!string.IsNullOrEmpty(entity.Namespace))
            {
                builder.Append("namespace ").Append(entity.Namespace).AppendLine();
                builder.AppendLine("{");
            }

            var indentation = string.IsNullOrEmpty(entity.Namespace) ? string.Empty : "    ";
            if (entity.GenerateSelectors)
            {
                AppendSelectors(builder, entity, indentation);
                builder.AppendLine();
            }
            else if (entity.SortableFields.Count > 0)
            {
                AppendDynamicSortingExtensions(builder, entity, indentation);
                builder.AppendLine();
            }

            AppendRepository(builder, entity, model.Settings, indentation);
            if (!string.IsNullOrEmpty(entity.Namespace))
            {
                builder.AppendLine("}");
            }
        }

        return builder.ToString().Replace(
            "    " + Environment.NewLine,
            Environment.NewLine,
            StringComparison.Ordinal);
    }

