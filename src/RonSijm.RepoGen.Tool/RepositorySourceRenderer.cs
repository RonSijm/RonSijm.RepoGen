        builder.Append(indentation).AppendLine("        global::System.Threading.CancellationToken cancellationToken = default)");
        builder.Append(indentation).AppendLine("    {");
        builder.Append(indentation).AppendLine("        var provider = RequireCacheProvider();");
        builder.Append(indentation).AppendLine("        return global::System.Threading.Tasks.Task.WhenAll(");
        for (var index = 0; index < entity.CacheInvalidationTags.Count; index++)
        {
            builder.Append(indentation).Append("            provider.InvalidateTagAsync(");
            if (string.Equals(entity.CacheInvalidationTags[index], entity.CacheTag, StringComparison.Ordinal))
            {
                builder.Append("CacheTag");
            }
            else
            {
                builder.Append('\"').Append(entity.CacheInvalidationTags[index]).Append('\"');
            }

            builder.Append(", cancellationToken)")
                .AppendLine(index == entity.CacheInvalidationTags.Count - 1 ? ");" : ",");
        }
        builder.Append(indentation).AppendLine("    }");
        builder.AppendLine();
        builder.Append(indentation).Append("    private ").Append(selector).Append(" WithCacheInvalidation(")
            .Append(selector).AppendLine(" source)");
        builder.Append(indentation).AppendLine("    {");
        builder.Append(indentation).AppendLine("        return new(source.SelectorContext, source.Query, InvalidateCacheAsync);");
        builder.Append(indentation).AppendLine("    }");
        builder.AppendLine();
        builder.Append(indentation).Append("    public ").Append(collectionSelector).AppendLine(" GetAllUnordered()");
        builder.Append(indentation).AppendLine("    {");
        builder.Append(indentation).AppendLine("        return WithCacheInvalidation(RequireInner().GetAllUnordered());");
        builder.Append(indentation).AppendLine("    }");
        builder.AppendLine();
        builder.Append(indentation).Append("    private ").Append(collectionSelector).Append(" WithCacheInvalidation(")
            .Append(collectionSelector).AppendLine(" source)");
        builder.Append(indentation).AppendLine("    {");
        builder.Append(indentation).AppendLine("        return new(source.SelectorContext, source.Query, InvalidateCacheAsync);");
        builder.Append(indentation).AppendLine("    }");
        builder.AppendLine();
        builder.Append(indentation).Append("    private ").Append(repositoryInterface).AppendLine(" RequireInner()");
        builder.Append(indentation).AppendLine("    {");
        builder.Append(indentation).AppendLine("        return inner ?? throw new global::System.InvalidOperationException(\"A repository to decorate is required.\");");
        builder.Append(indentation).AppendLine("    }");
        builder.AppendLine();
        builder.Append(indentation).AppendLine("    private global::RonSijm.RepoGen.IRepositoryCacheProvider RequireCacheProvider()");
        builder.Append(indentation).AppendLine("    {");
        builder.Append(indentation).AppendLine("        return cacheProvider ?? throw new global::System.InvalidOperationException(\"A repository cache provider is required.\");");
        builder.Append(indentation).AppendLine("    }");
        builder.Append(indentation).AppendLine("}");
    }

    private static void AppendCacheDecoratorLookup(
        StringBuilder builder,
        string indentation,
        string repositoryInterface,
        string selector,
        string collectionSelector,
        string methodName,
        bool isUnique,
        string parameters,
        string arguments)
    {
        var selectorType = isUnique ? selector : collectionSelector;
        builder.Append(indentation).Append("    public ").Append(selectorType).Append(' ')
            .Append(methodName).Append('(').Append(parameters).AppendLine(")");
        builder.Append(indentation).AppendLine("    {");
        builder.Append(indentation).Append("        return WithCacheInvalidation(RequireInner().")
            .Append(methodName).Append('(').Append(arguments).AppendLine("));");
        builder.Append(indentation).AppendLine("    }");
        builder.AppendLine();
    }

    private static string RenderParameters(LookupModel lookup) =>
        string.Join(", ", lookup.Properties.Select(static property => property.TypeName + " " + property.ParameterName));

    private static string RenderArgumentNames(LookupModel lookup) =>
        string.Join(", ", lookup.Properties.Select(static property => property.ParameterName));

    private static string RenderParameters(FilterModel filter) =>
        string.Join(", ", filter.Parameters.Select(static parameter => parameter.TypeName + " " + parameter.Name));

    private static string RenderArgumentNames(FilterModel filter) =>
        string.Join(", ", filter.Parameters.Select(static parameter => parameter.Name));

    private static string RenderPredicate(LookupModel lookup) =>
        string.Join(
            " && ",
            lookup.Properties.Select(static property =>
                "entity." + RepositoryModelFactory.EscapeIdentifier(property.PropertyName) + " == " + property.ParameterName));

    private static string RenderBaseQuery(
        EntityRepositoryModel entity,
        RepositoryGenerationSettingsModel settings)
    {
        var query = "context.Set<" + entity.EntityTypeName + ">()";
        query = settings.DefaultTrackingBehavior switch
        {
            RonSijm.RepoGen.Design.RepositoryTrackingBehavior.Tracking =>
                "global::Microsoft.EntityFrameworkCore.EntityFrameworkQueryableExtensions.AsTracking(" + query + ")",
            RonSijm.RepoGen.Design.RepositoryTrackingBehavior.NoTracking =>
                "global::Microsoft.EntityFrameworkCore.EntityFrameworkQueryableExtensions.AsNoTracking(" + query + ")",
            RonSijm.RepoGen.Design.RepositoryTrackingBehavior.NoTrackingWithIdentityResolution =>
                "global::Microsoft.EntityFrameworkCore.EntityFrameworkQueryableExtensions.AsNoTrackingWithIdentityResolution(" + query + ")",
            _ => query
        };

        foreach (var include in entity.Includes)
        {
            query = "global::Microsoft.EntityFrameworkCore.EntityFrameworkQueryableExtensions.Include(" +
                    query + ", " + include.ExpressionSource + ")";
        }

        return query;
    }

    private static string RenderCollectionQuery(EntityRepositoryModel entity, string query)
    {
        for (var index = 0; index < entity.DefaultSorts.Count; index++)
        {
            var sort = entity.DefaultSorts[index];
            var method = index == 0
                ? sort.IsDescending ? "OrderByDescending" : "OrderBy"
                : sort.IsDescending
                    ? "ThenByDescending"
                    : "ThenBy";
            query = "global::System.Linq.Queryable." + method + "(" + query + ", " + sort.ExpressionSource + ")";
        }

        return query;
    }
