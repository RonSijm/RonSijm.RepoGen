using System.Text;
using RonSijm.RepoGen.Design;

namespace RonSijm.RepoGen.Tool;

internal static class ProjectionSourceRenderer
{
    public static string Render(RepositoryGenerationModel model)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");

        var groups = model.Entities
            .SelectMany(entity => entity.Projections.Select(projection => new { Entity = entity, Projection = projection }))
            .GroupBy(
                static item => new { item.Projection.Namespace, item.Entity.EntityName },
                static item => item)
            .OrderBy(static group => group.Key.Namespace, StringComparer.Ordinal)
            .ThenBy(static group => group.Key.EntityName, StringComparer.Ordinal);

        foreach (var group in groups)
        {
            builder.AppendLine();
            if (!string.IsNullOrEmpty(group.Key.Namespace))
            {
                builder.Append("namespace ").Append(group.Key.Namespace).AppendLine();
                builder.AppendLine("{");
            }

            var indentation = string.IsNullOrEmpty(group.Key.Namespace) ? string.Empty : "    ";
            var entity = group.First().Entity;
            builder.Append(indentation).Append(model.Settings.CqrsSelectors && !entity.WriteEnabled ? "internal" : entity.Accessibility).Append(" static class ").Append(entity.EntityName)
                .AppendLine("ConfiguredProjectionExtensions");
            builder.Append(indentation).AppendLine("{");

            foreach (var item in group.OrderBy(static item => item.Projection.SingleMethodName, StringComparer.Ordinal))
            {
                AppendProjectionMethods(builder, item.Entity, item.Projection, model.Settings, indentation + "    ");
            }

            builder.Append(indentation).AppendLine("}");
            if (!string.IsNullOrEmpty(group.Key.Namespace))
            {
                builder.AppendLine("}");
            }
        }

        AppendConfiguredQueries(builder, model);

        return builder.ToString();
    }

    private static void AppendConfiguredQueries(StringBuilder builder, RepositoryGenerationModel model)
    {
        var groups = model.Entities
            .SelectMany(entity => entity.Queries.Where(static query => query.RegisteredRoot is null).Select(query => new { Entity = entity, Query = query }))
            .GroupBy(
                static item => new { item.Query.Namespace, item.Entity.EntityName },
                static item => item)
            .OrderBy(static group => group.Key.Namespace, StringComparer.Ordinal)
            .ThenBy(static group => group.Key.EntityName, StringComparer.Ordinal);

        foreach (var group in groups)
        {
            builder.AppendLine();
            if (!string.IsNullOrEmpty(group.Key.Namespace))
            {
                builder.Append("namespace ").Append(group.Key.Namespace).AppendLine();
                builder.AppendLine("{");
            }

            var indentation = string.IsNullOrEmpty(group.Key.Namespace) ? string.Empty : "    ";
            var entity = group.First().Entity;
            builder.Append(indentation).Append(model.Settings.CqrsSelectors ? "internal" : entity.Accessibility).Append(" static class ")
                .Append(entity.EntityName).AppendLine("ConfiguredQueryExtensions");
            builder.Append(indentation).AppendLine("{");
            foreach (var item in group.OrderBy(static item => item.Query.MethodName, StringComparer.Ordinal))
            {
                AppendConfiguredQuery(builder, model.Settings.CqrsSelectors ? item.Entity with { Accessibility = "internal" } : item.Entity,
                    item.Query, indentation + "    ");
            }

            if (group.Any(static item => item.Query.Pipeline?.Stages.Any(static stage => stage.Kind is RepositoryQueryStageKind.ThenBy or RepositoryQueryStageKind.ThenByDescending) == true))
            {
                ResultPipelineSourceRenderer.AppendOrderingHelper(builder, indentation + "    ",
                    group.Any(static item => item.Query.Pipeline?.Stages.Any(static stage => stage.FieldSort is not null) == true));
            }

            builder.Append(indentation).AppendLine("}");
            if (!string.IsNullOrEmpty(group.Key.Namespace))
            {
                builder.AppendLine("}");
            }
        }
    }

    private static void AppendConfiguredQuery(
        StringBuilder builder,
        EntityRepositoryModel entity,
        ConfiguredQueryModel query,
        string indentation)
    {
        var repository = Qualify(entity.Namespace, "I" + entity.EntityName + "Repository");
        var cacheableRepository = Qualify(entity.Namespace, "ICacheable" + entity.EntityName + "Repository");
        var returnType = RenderQueryReturnType(query);
        var parameters = CreateQueryParameters(query);
        var argumentNames = parameters.Select(static parameter => parameter.Name).ToArray();
        var accessibility = entity.Accessibility == "public" && query.Accessibility == "public"
            ? "public"
            : "internal";

        builder.Append(indentation).Append(accessibility).Append(" static ").Append(returnType).Append(' ')
            .Append(query.MethodName).AppendLine("(");
        builder.Append(indentation).Append("    this ").Append(repository).AppendLine(" repository,");
        AppendMethodParameters(builder, parameters, indentation + "    ", includeCancellationToken: true);
        builder.Append(indentation).AppendLine(")");
        builder.Append(indentation).AppendLine("{");
        builder.Append(indentation).AppendLine("    if (repository is null)");
        builder.Append(indentation).AppendLine("    {");
        builder.Append(indentation).AppendLine("        throw new global::System.ArgumentNullException(nameof(repository));");
        builder.Append(indentation).AppendLine("    }");
        ClosedRepositorySourceRenderer.AppendValidations(builder, query.Validations, indentation + "    ");
        if (RepositoryQueryPreparationSourceRenderer.Required(query))
        {
            RepositoryQueryPreparationSourceRenderer.AppendPreparation(builder, query, indentation + "    ");
            builder.Append(indentation).Append("    return ").Append(query.MethodName).Append("Prepared(repository, ")
                .Append(string.Join(", ", argumentNames.Concat(RepositoryQueryPreparationSourceRenderer.Arguments(query)).Append("cancellationToken"))).AppendLine(");");
            builder.Append(indentation).AppendLine("}").AppendLine();
            builder.Append(indentation).Append("internal static ").Append(returnType).Append(' ').Append(query.MethodName).AppendLine("Prepared(");
            builder.Append(indentation).Append("    ").Append(repository).AppendLine(" repository,");
            AppendMethodParameters(builder, parameters.Concat(RepositoryQueryPreparationSourceRenderer.Parameters(query)).ToList(), indentation + "    ", includeCancellationToken: true);
            builder.Append(indentation).AppendLine(")").Append(indentation).AppendLine("{");
        }

        var coreArgumentNames = argumentNames.Concat(RepositoryQueryPreparationSourceRenderer.Arguments(query)).ToArray();
        if (query.Cache.Enabled)
        {
            builder.AppendLine();
            builder.Append(indentation).Append("    if (repository is ").Append(cacheableRepository)
                .AppendLine(" cacheableRepository)");
            builder.Append(indentation).AppendLine("    {");
            var cacheIdentity = query.MethodName;
            if (RepositoryQueryPreparationSourceRenderer.Required(query) || query.Dictionary is { DuplicateKeys: not RepositoryDuplicateKeyBehavior.Throw })
            {
                cacheIdentity += ":" + global::System.Convert.ToHexString(global::System.Security.Cryptography.SHA256.HashData(
                    global::System.Text.Encoding.UTF8.GetBytes(global::System.Text.Json.JsonSerializer.Serialize(query))));
            }

            builder.Append(indentation).Append("        var cacheKey = \"").Append(EscapeString(cacheIdentity)).AppendLine(":\" +");
            builder.Append(indentation).Append("            global::System.Text.Json.JsonSerializer.Serialize(new object?[] { ")
                .Append(string.Join(", ", coreArgumentNames)).AppendLine(" });");
            builder.Append(indentation).AppendLine("        return cacheableRepository.GetOrCreateCachedAsync(");
            builder.Append(indentation).AppendLine("            cacheKey,");
            builder.Append(indentation).Append("            ").Append(RenderCacheOptions(query.Cache, query.InfrastructurePrefix)).AppendLine(",");
            builder.Append(indentation).Append("            (source, token) => ").Append(query.MethodName)
                .Append("Core(source");
            foreach (var argument in coreArgumentNames)
            {
                builder.Append(", ").Append(argument);
            }

            builder.AppendLine(", token),");
            builder.Append(indentation).AppendLine("            cancellationToken);");
            builder.Append(indentation).AppendLine("    }");
        }

        builder.AppendLine();
        builder.Append(indentation).Append("    return ").Append(query.MethodName).Append("Core(repository");
        foreach (var argument in coreArgumentNames)
        {
            builder.Append(", ").Append(argument);
        }

        builder.AppendLine(", cancellationToken);");
        builder.Append(indentation).AppendLine("}");
        builder.AppendLine();

        builder.Append(indentation).Append("private static ").Append(query.Pipeline is null && query.PageConsistency == RepositoryPageConsistency.BestEffort ? "" : "async ").Append(returnType).Append(' ').Append(query.MethodName)
            .AppendLine("Core(");
        builder.Append(indentation).Append("    ").Append(repository).AppendLine(" repository,");
        AppendMethodParameters(builder, parameters.Concat(RepositoryQueryPreparationSourceRenderer.Parameters(query)).ToList(), indentation + "    ", includeCancellationToken: true,
            iteratorCancellation: query.Pipeline is not null && query.ResultKind == RepositoryQueryResultKind.Stream);
        builder.Append(indentation).AppendLine(")");
        builder.Append(indentation).AppendLine("{");
        builder.Append(indentation).Append("    var selector = repository.");
        if (query.Source is null && entity.VisibilityPolicies is { Count: > 0 })
        {
            builder.Append("GetAllForQuery(\"").Append(RepositoryOperationSignature.Query(query)).AppendLine("\");");
        }
        else
        {
            builder.Append(query.UseDefaultSort && query.Source is null ? "GetAll" : "GetAllUnordered").AppendLine("();");
        }

        if (query.PageConsistency != RepositoryPageConsistency.BestEffort)
        {
            builder.Append(indentation).AppendLine("    await using var __repoGenReadTransaction = await global::RonSijm.RepoGen.EntityFrameworkCore.RepositoryReadTransaction.AcquireAsync(selector.SelectorContext!, cancellationToken).ConfigureAwait(false);");
        }

        foreach (var predicate in query.Predicates)
        {
            if (predicate.ConditionSource is not null)
            {
                builder.Append(indentation).Append("    if (").Append(predicate.ConditionSource).AppendLine(")");
            }

            builder.Append(indentation).Append(predicate.ConditionSource is null ? "    " : "        ").Append("selector = selector.Where(entity => ")
                .Append(predicate.PredicateSource).AppendLine(");");
        }

        foreach (var include in query.Includes)
        {
            builder.Append(indentation).Append("    selector = ").Append(RepositoryIncludeSourceRenderer.ApplySelector("selector", include)).AppendLine(";");
        }

        for (var index = 0; index < query.Sorts.Count; index++)
        {
            var sort = query.Sorts[index];
            var method = index == 0
                ? sort.IsDescending ? "OrderByDescending" : "OrderBy"
                : sort.IsDescending
                    ? "ThenByDescending"
                    : "ThenBy";
            builder.Append(indentation).Append("    selector = selector.").Append(method).Append('(')
                .Append(sort.ExpressionSource).AppendLine(");");
        }

        if (query.DynamicSort is not null)
        {
            builder.Append(indentation).Append("    if (");
            for (var index = 0; index < query.DynamicSort.Fields.Count; index++)
            {
                if (index > 0)
                {
                    builder.Append(" && ");
                }

                builder.Append("!global::System.String.Equals(")
                    .Append(query.DynamicSort.FieldNameParameter).Append(", \"")
                    .Append(EscapeString(query.DynamicSort.Fields[index].PropertyName))
                    .Append("\", global::System.StringComparison.OrdinalIgnoreCase)");
            }

            builder.AppendLine(")");
            builder.Append(indentation).AppendLine("    {");
            builder.Append(indentation).Append("        throw new global::System.ArgumentOutOfRangeException(nameof(")
                .Append(query.DynamicSort.FieldNameParameter).Append("), ")
                .Append(query.DynamicSort.FieldNameParameter).Append(", \"Sortable fields for this query: ")
                .Append(string.Join(", ", query.DynamicSort.Fields.Select(static field => field.PropertyName)))
                .AppendLine(".\");");
            builder.Append(indentation).AppendLine("    }");
            builder.Append(indentation).Append("    selector = selector.OrderBy(")
                .Append(query.DynamicSort.FieldNameParameter).Append(", ")
                .Append(query.DynamicSort.DescendingParameter).AppendLine(");");
        }

        if (query.Source is null)
        {
            AppendQueryPolicies(builder, query, indentation + "    ");
        }

        if (query.ResultKind == RepositoryQueryResultKind.CursorPaged && query.Cursor?.OnResults != true)
        {
            builder.Append(indentation).AppendLine("    if (cursorPage.HasCursor)");
            builder.Append(indentation).AppendLine("    {");
            builder.Append(indentation).AppendLine("        var cursor = cursorPage.Cursor!;");
            builder.Append(indentation).Append("        selector = selector.Where(entity => ")
                .Append(query.Cursor!.SeekPredicateBodySource).AppendLine(");");
            builder.Append(indentation).AppendLine("    }");
            builder.AppendLine();
        }

        if (query.Pipeline is not null)
        {
            ResultPipelineSourceRenderer.Append(builder, query, indentation + "    ");
        }
        else
        {
            builder.Append(indentation).Append("    return ").Append(query.PageConsistency == RepositoryPageConsistency.BestEffort ? "" : "await ")
                .Append(RenderQueryTerminal(entity, query)).AppendLine(query.PageConsistency == RepositoryPageConsistency.BestEffort ? ";" : ".ConfigureAwait(false);");
        }

        builder.Append(indentation).AppendLine("}");
        builder.AppendLine();
    }

    private static void AppendQueryPolicies(StringBuilder builder, ConfiguredQueryModel query, string indentation)
    {
        var trackingMethod = query.TrackingBehavior switch
        {
            RepositoryTrackingBehavior.Tracking => "AsTracking",
            RepositoryTrackingBehavior.NoTracking => "AsNoTracking",
            RepositoryTrackingBehavior.NoTrackingWithIdentityResolution => "AsNoTrackingWithIdentityResolution",
            _ => null
        };
        if (trackingMethod is not null)
        {
            builder.Append(indentation).Append("selector = selector.ConfigureQuery(static source => global::Microsoft.EntityFrameworkCore.EntityFrameworkQueryableExtensions.")
                .Append(trackingMethod).AppendLine("(source));");
        }

        if (query.IgnoreQueryFilters)
        {
            builder.Append(indentation).AppendLine("selector = selector.ConfigureQuery(static source => global::Microsoft.EntityFrameworkCore.EntityFrameworkQueryableExtensions.IgnoreQueryFilters(source));");
        }

        if (query.IgnoreAutoIncludes)
        {
            builder.Append(indentation).AppendLine("selector = selector.ConfigureQuery(static source => global::Microsoft.EntityFrameworkCore.EntityFrameworkQueryableExtensions.IgnoreAutoIncludes(source));");
        }

        if (query.SplittingBehavior != RepositoryQuerySplittingBehavior.Unspecified)
        {
            var method = query.SplittingBehavior == RepositoryQuerySplittingBehavior.SplitQuery
                ? "AsSplitQuery"
                : "AsSingleQuery";
            builder.Append(indentation).Append("selector = selector.ConfigureQuery(static source => global::Microsoft.EntityFrameworkCore.RelationalQueryableExtensions.")
                .Append(method).AppendLine("(source));");
        }

        if (query.QueryTag is not null)
        {
            builder.Append(indentation).Append("selector = selector.ConfigureQuery(static source => global::Microsoft.EntityFrameworkCore.EntityFrameworkQueryableExtensions.TagWith(source, \"")
                .Append(EscapeString(query.QueryTag)).AppendLine("\"));");
        }
    }

    private static string RenderQueryTerminal(EntityRepositoryModel entity, ConfiguredQueryModel query)
    {
        var cancellation = "cancellationToken";
        var selector = entity.ProjectionEnabled
            ? "selector"
            : $"(({query.InfrastructurePrefix}BaseCollectionSelector<{entity.EntityTypeName}>)selector)";
        return query.ResultKind switch
        {
            RepositoryQueryResultKind.List => $"{selector}.ProjectToListAsync({query.ProjectionExpressionSource}, {cancellation})",
            RepositoryQueryResultKind.Single => $"{selector}.ProjectToSingleAsync({query.ProjectionExpressionSource}, {cancellation})",
            RepositoryQueryResultKind.SingleOrDefault => $"{selector}.ProjectToSingleOrDefaultAsync({query.ProjectionExpressionSource}, {cancellation})",
            RepositoryQueryResultKind.FirstOrDefault => $"{selector}.ProjectToFirstOrDefaultAsync({query.ProjectionExpressionSource}, {cancellation})",
            RepositoryQueryResultKind.Paged => $"{selector}.ToPagedListAsync({query.ProjectionExpressionSource}, page, pageSize, {cancellation})",
            RepositoryQueryResultKind.CursorPaged => $"{selector}.ToCursorPagedListAsync({query.ProjectionExpressionSource}, {query.Cursor!.CursorSelectorExpressionSource}, cursorPage.PageSize, {cancellation})",
            RepositoryQueryResultKind.GroupedList => $"{selector}.GroupBy({query.Group!.KeySelectorExpressionSource}).ProjectToListAsync({query.Group.ProjectionExpressionSource}, {cancellation})",
            RepositoryQueryResultKind.Exists => $"{Qualify(entity.Namespace, entity.EntityName + "CollectionSelectorExtensions")}.ExistsAsync(selector, {cancellation})",
            RepositoryQueryResultKind.Count => $"{Qualify(entity.Namespace, entity.EntityName + "CollectionSelectorExtensions")}.CountAsync(selector, {cancellation})",
            RepositoryQueryResultKind.Stream => $"{selector}.StreamAsync({query.ProjectionExpressionSource}, {cancellation})",
            _ => throw new InvalidOperationException($"Unsupported configured query result kind '{query.ResultKind}'.")
        };
    }

    internal static string RenderQueryReturnType(ConfiguredQueryModel query) => query.ResultKind switch
    {
        RepositoryQueryResultKind.List => $"global::System.Threading.Tasks.Task<global::System.Collections.Generic.IReadOnlyList<{query.ResultTypeName}>>",
        RepositoryQueryResultKind.Single => $"global::System.Threading.Tasks.Task<{query.ResultTypeName}>",
        RepositoryQueryResultKind.SingleOrDefault or RepositoryQueryResultKind.FirstOrDefault =>
            $"global::System.Threading.Tasks.Task<{NullableType(query.ResultTypeName)}>",
        RepositoryQueryResultKind.Paged => $"global::System.Threading.Tasks.Task<{query.InfrastructurePrefix}PagedResult<{query.ResultTypeName}>>",
        RepositoryQueryResultKind.CursorPaged =>
            $"global::System.Threading.Tasks.Task<{query.InfrastructurePrefix}CursorPagedResult<{query.ResultTypeName}, {query.Cursor!.CursorTypeName}>>",
        RepositoryQueryResultKind.GroupedList =>
            $"global::System.Threading.Tasks.Task<global::System.Collections.Generic.IReadOnlyList<{query.ResultTypeName}>>",
        RepositoryQueryResultKind.Exists => "global::System.Threading.Tasks.Task<bool>",
        RepositoryQueryResultKind.Count => "global::System.Threading.Tasks.Task<int>",
        RepositoryQueryResultKind.Stream => $"global::System.Collections.Generic.IAsyncEnumerable<{query.ResultTypeName}>",
        RepositoryQueryResultKind.Dictionary => $"global::System.Threading.Tasks.Task<global::System.Collections.Generic.IReadOnlyDictionary<{query.Dictionary!.KeyTypeName}, {query.Dictionary.ValueTypeName}>>",
        RepositoryQueryResultKind.Lookup => $"global::System.Threading.Tasks.Task<global::System.Collections.Generic.IReadOnlyDictionary<{query.Dictionary!.KeyTypeName}, global::System.Collections.Generic.IReadOnlyList<{query.Dictionary.ValueTypeName}>>>",
        RepositoryQueryResultKind.Slice => $"global::System.Threading.Tasks.Task<global::RonSijm.RepoGen.Abstractions.SliceResult<{query.ResultTypeName}>>",
        RepositoryQueryResultKind.Max or RepositoryQueryResultKind.Min or RepositoryQueryResultKind.Sum or RepositoryQueryResultKind.Average =>
            $"global::System.Threading.Tasks.Task<{query.Scalar!.ReturnTypeName}>",
        _ => throw new InvalidOperationException($"Unsupported configured query result kind '{query.ResultKind}'.")
    };

    private static string NullableType(string typeName) => typeName.EndsWith('?') ? typeName : typeName + "?";

    internal static List<(string Type, string Name)> CreateQueryParameters(ConfiguredQueryModel query)
    {
        var parameters = query.Parameters.Select(static parameter => (parameter.TypeName, parameter.Name)).ToList();
        if (query.ResultKind is RepositoryQueryResultKind.Paged or RepositoryQueryResultKind.Slice)
        {
            parameters.Add(("int", "page"));
            parameters.Add(("int", "pageSize"));
        }
        else if (query.ResultKind == RepositoryQueryResultKind.CursorPaged)
        {
            parameters.Add(($"{query.InfrastructurePrefix}CursorPageRequest<{query.Cursor!.CursorTypeName}>", "cursorPage"));
        }

        return parameters;
    }

    private static void AppendMethodParameters(
        StringBuilder builder,
        List<(string Type, string Name)> parameters,
        string indentation,
        bool includeCancellationToken,
        bool iteratorCancellation = false)
    {
        for (var index = 0; index < parameters.Count; index++)
        {
            builder.Append(indentation).Append(parameters[index].Type).Append(' ').Append(parameters[index].Name).AppendLine(",");
        }

        if (includeCancellationToken)
        {
            if (iteratorCancellation)
            {
                builder.Append(indentation).AppendLine("[global::System.Runtime.CompilerServices.EnumeratorCancellation]");
            }

            builder.Append(indentation).AppendLine("global::System.Threading.CancellationToken cancellationToken = default");
        }
    }

    private static string RenderCacheOptions(ConfiguredQueryCacheModel cache, string infrastructurePrefix)
    {
        var absolute = cache.AbsoluteExpirationTicks is long absoluteTicks
            ? $"global::System.TimeSpan.FromTicks({absoluteTicks}L)"
            : "null";
        var sliding = cache.SlidingExpirationTicks is long slidingTicks
            ? $"global::System.TimeSpan.FromTicks({slidingTicks}L)"
            : "null";
        return $"new {infrastructurePrefix}RepositoryCacheEntryOptions({absolute}, {sliding})";
    }

    private static string EscapeString(string value) =>
        value.Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal)
            .Replace("\r", "\\r", StringComparison.Ordinal)
            .Replace("\n", "\\n", StringComparison.Ordinal);

    private static void AppendProjectionMethods(
        StringBuilder builder,
        EntityRepositoryModel entity,
        ProjectionModel projection,
        RepositoryGenerationSettingsModel settings,
        string indentation)
    {
        var selectorType = Qualify(entity.Namespace, entity.EntityName + "Selector");
        var collectionSelectorType = Qualify(entity.Namespace, entity.EntityName + "CollectionSelector");
        var accessibility = entity.Accessibility == "public" && projection.Accessibility == "public"
            ? "public"
            : "internal";

        builder.Append(indentation).Append(accessibility).Append(" static global::System.Threading.Tasks.Task<")
            .Append(NullableType(projection.ProjectionTypeName)).Append("> ").Append(projection.SingleMethodName).AppendLine("(");
        builder.Append(indentation).Append("    this ").Append(selectorType).AppendLine(" selector,");
        builder.Append(indentation).AppendLine("    global::System.Threading.CancellationToken cancellationToken = default)");
        builder.Append(indentation).AppendLine("{");
        var singleSelector = RenderProjectionSelector(entity, projection, settings, collection: false);
        builder.Append(indentation).Append("    return ").Append(singleSelector)
            .Append(".ProjectToAsync(").Append(projection.NullableExpressionSource ?? projection.ExpressionSource)
            .AppendLine(", cancellationToken);");
        builder.Append(indentation).AppendLine("}");
        builder.AppendLine();
        builder.Append(indentation).Append(accessibility).Append(" static global::System.Threading.Tasks.Task<global::System.Collections.Generic.IReadOnlyList<")
            .Append(projection.ProjectionTypeName).Append(">> ").Append(projection.CollectionMethodName).AppendLine("(");
        builder.Append(indentation).Append("    this ").Append(collectionSelectorType).AppendLine(" selector,");
        builder.Append(indentation).AppendLine("    global::System.Threading.CancellationToken cancellationToken = default)");
        builder.Append(indentation).AppendLine("{");
        var collectionSelector = RenderProjectionSelector(entity, projection, settings, collection: true);
        builder.Append(indentation).Append("    return ").Append(collectionSelector)
            .Append(".ProjectToListAsync(").Append(projection.ExpressionSource)
            .AppendLine(", cancellationToken);");
        builder.Append(indentation).AppendLine("}");
        builder.AppendLine();
    }

    private static string RenderSelectorWithIncludes(ProjectionModel projection)
    {
        var selector = "selector";
        foreach (var include in projection.Includes)
        {
            selector = RepositoryIncludeSourceRenderer.ApplySelector(selector, include);
        }

        return selector;
    }

    private static string RenderProjectionSelector(
        EntityRepositoryModel entity,
        ProjectionModel projection,
        RepositoryGenerationSettingsModel settings,
        bool collection)
    {
        var selector = RenderSelectorWithIncludes(projection);
        if (entity.ProjectionEnabled)
        {
            return selector;
        }

        var baseSelector = collection ? "BaseCollectionSelector" : "BaseEntitySelector";
        return $"(({settings.InfrastructurePrefix}{baseSelector}<{entity.EntityTypeName}>){selector})";
    }

    private static string Qualify(string @namespace, string typeName) =>
        string.IsNullOrEmpty(@namespace) ? "global::" + typeName : "global::" + @namespace + "." + typeName;
}
