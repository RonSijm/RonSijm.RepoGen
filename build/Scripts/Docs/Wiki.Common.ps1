Set-StrictMode -Version Latest

$script:RepoGenWikiMarker = '<!-- Generated by RepoGen wiki publisher. Edit the repository source, not this page. -->'
$script:RepoGenWikiManifest = '.repogen-generated-files'

function Test-WikiPathInside {
    param([string] $Root, [string] $Path)
    $rootPath = [IO.Path]::GetFullPath($Root).TrimEnd([IO.Path]::DirectorySeparatorChar, [IO.Path]::AltDirectorySeparatorChar)
    $candidate = [IO.Path]::GetFullPath($Path)
    $comparison = if ($IsWindows) { [StringComparison]::OrdinalIgnoreCase } else { [StringComparison]::Ordinal }
    return $candidate.Equals($rootPath, $comparison) -or $candidate.StartsWith($rootPath + [IO.Path]::DirectorySeparatorChar, $comparison)
}

function Assert-WikiUnlinkedPath {
    param([string] $Path)
    $candidate = [IO.Path]::GetFullPath($Path)
    while ($candidate) {
        $item = Get-Item -LiteralPath $candidate -Force -ErrorAction Ignore
        if ($null -ne $item) {
            if (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0 -or $item.LinkType) {
                throw "Linked paths are not supported by the wiki publisher: $candidate"
            }
        }
        $candidate = [IO.Path]::GetDirectoryName($candidate)
    }
}

function Get-WikiManagedPath {
    param([string] $Root, [string] $FileName)
    if ($FileName -notmatch '^(?:[A-Za-z0-9][A-Za-z0-9._-]*|_Sidebar)\.md$' -or
        $FileName -match '^(?i)(?:CON|PRN|AUX|NUL|COM[1-9]|LPT[1-9])(?:\..*)?$') {
        throw "Invalid generated wiki filename: $FileName"
    }
    $rootPath = [IO.Path]::GetFullPath($Root)
    $target = [IO.Path]::GetFullPath((Join-Path $rootPath $FileName))
    if (!(Test-WikiPathInside $rootPath $target) -or [IO.Path]::GetDirectoryName($target) -ne $rootPath) {
        throw "Generated wiki path escapes its directory: $FileName"
    }
    Assert-WikiUnlinkedPath $target
    if ((Test-Path -LiteralPath $target) -and !(Test-Path -LiteralPath $target -PathType Leaf)) {
        throw "A generated wiki page is not a regular file: $target"
    }
    return $target
}

function Read-WikiManagedFiles {
    param([string] $Root, [switch] $Required)
    $manifest = Join-Path ([IO.Path]::GetFullPath($Root)) $script:RepoGenWikiManifest
    Assert-WikiUnlinkedPath $manifest
    if ((Test-Path -LiteralPath $manifest) -and !(Test-Path -LiteralPath $manifest -PathType Leaf)) {
        throw "Generated wiki manifest is not a regular file: $manifest"
    }
    if (!(Test-Path -LiteralPath $manifest -PathType Leaf)) {
        if ($Required) { throw "Generated wiki manifest is missing: $manifest" }
        return
    }
    $seen = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    foreach ($name in [IO.File]::ReadAllLines($manifest)) {
        if ([string]::IsNullOrWhiteSpace($name)) { continue }
        [void](Get-WikiManagedPath $Root $name)
        if (!$seen.Add($name)) { throw "Duplicate generated wiki filename: $name" }
        $name
    }
}

function Assert-WikiOwnedPage {
    param([string] $Path, [switch] $AllowInitialPage)
    if (!(Test-Path -LiteralPath $Path)) { return }
    if ($AllowInitialPage -and [IO.Path]::GetFileName($Path) -in @('Home.md', '_Sidebar.md')) { return }
    $reader = [IO.File]::OpenText($Path)
    try { $firstLine = $reader.ReadLine() } finally { $reader.Dispose() }
    if ($firstLine -ne $script:RepoGenWikiMarker) {
        throw "Refusing to replace or remove a handwritten wiki page: $Path"
    }
}

function Write-WikiManagedPages {
    param(
        [string] $Root,
        [Collections.Generic.Dictionary[string, string]] $Pages,
        [switch] $AllowInitialPages
    )
    Assert-WikiUnlinkedPath $Root
    $rootPath = [IO.Path]::GetFullPath($Root)
    $previous = @(Read-WikiManagedFiles $rootPath)
    $names = [string[]]@($Pages.Keys)
    [Array]::Sort($names, [StringComparer]::Ordinal)
    foreach ($name in $names) {
        $target = Get-WikiManagedPath $rootPath $name
        Assert-WikiOwnedPage $target -AllowInitialPage:$AllowInitialPages
        if (!$Pages[$name].StartsWith($script:RepoGenWikiMarker + [char]10, [StringComparison]::Ordinal)) {
            throw "A generated wiki page has no ownership marker: $name"
        }
    }
    foreach ($name in $previous) {
        if (!$Pages.ContainsKey($name)) { Assert-WikiOwnedPage (Get-WikiManagedPath $rootPath $name) }
    }
    # All names/ownership are checked before changing anything. Never clear the whole directory.
    [void][IO.Directory]::CreateDirectory($rootPath)
    foreach ($name in $previous) {
        if (!$Pages.ContainsKey($name)) {
            $target = Get-WikiManagedPath $rootPath $name
            if (Test-Path -LiteralPath $target) { Remove-Item -LiteralPath $target -Force }
        }
    }
    foreach ($name in $names) {
        [IO.File]::WriteAllText((Get-WikiManagedPath $rootPath $name), $Pages[$name], [Text.UTF8Encoding]::new($false))
    }
    [IO.File]::WriteAllText((Join-Path $rootPath $script:RepoGenWikiManifest), ($names -join [char]10) + [char]10, [Text.UTF8Encoding]::new($false))
}
