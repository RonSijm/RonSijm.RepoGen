using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Design;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Scaffolding;
using Microsoft.EntityFrameworkCore.SqlServer.Design.Internal;
using Microsoft.Extensions.DependencyInjection;

namespace RonSijm.RepoGen.AdventureWorks.Scaffolding;

internal static class Program
{
    private static readonly JsonSerializerOptions JsonOptions = new() { WriteIndented = true };

    private static int Main(string[] args)
    {
        if (args.Length is < 1 or > 2 || args.Length == 2 && args[1] != "--check")
        {
            Console.Error.WriteLine("Usage: AdventureWorks.Scaffolding <example-directory> [--check]");
            return 2;
        }

        var root = Path.GetFullPath(args[0]);
        var source = Path.Combine(root, "sql-server-samples/samples/databases/adventure-works/oltp-install-script/instawdb.sql");
        if (!File.Exists(source))
        {
            Console.Error.WriteLine("Initialize the AdventureWorks git submodule before scaffolding. See README.md.");
            return 2;
        }

        var schema = SchemaReader.Read(source);
        using var context = new DbContext(new DbContextOptionsBuilder()
            .UseSqlServer("Server=(localdb)\\MSSQLLocalDB;Database=AdventureWorks;Integrated Security=true",
                options => options.UseHierarchyId().UseNetTopologySuite()).Options);
        var services = new ServiceCollection();
        services.AddDbContextDesignTimeServices(context);
#pragma warning disable EF1001 // Provider design-time services are pinned with the scaffolder.
        new SqlServerDesignTimeServices().ConfigureDesignTimeServices(services);
        new SqlServerHierarchyIdDesignTimeServices().ConfigureDesignTimeServices(services);
        new SqlServerNetTopologySuiteDesignTimeServices().ConfigureDesignTimeServices(services);
#pragma warning restore EF1001
        services.AddEntityFrameworkDesignTimeServices();
        services.AddSingleton<IScaffoldingModelFactory, ExplicitJoinModelFactory>();
        using var provider = services.BuildServiceProvider();
        var model = provider.GetRequiredService<IScaffoldingModelFactory>().Create(schema, new ModelReverseEngineerOptions());
        var options = new ModelCodeGenerationOptions
        {
            ContextName = "AdventureWorksContext",
            ModelNamespace = "RonSijm.RepoGen.AdventureWorks.Model",
            ContextNamespace = "RonSijm.RepoGen.AdventureWorks.Model",
            Language = "C#",
            UseNullableReferenceTypes = true,
            SuppressOnConfiguring = true,
            SuppressConnectionStringWarning = true,
            ConnectionString = "Server=(localdb)\\MSSQLLocalDB;Database=AdventureWorks;Integrated Security=true"
        };
        var scaffolded = provider.GetRequiredService<IModelCodeGeneratorSelector>().Select(options).GenerateModel(model, options);
        if (scaffolded.AdditionalFiles.Count != schema.Tables.Count ||
            model.GetEntityTypes().Sum(entity => entity.GetProperties().Count()) != schema.Tables.Sum(table => table.Columns.Count) ||
            model.GetEntityTypes().Sum(entity => entity.GetForeignKeys().Count()) != schema.Tables.Sum(table => table.ForeignKeys.Count))
        {
            foreach (var table in schema.Tables)
            {
                var entity = model.GetEntityTypes().SingleOrDefault(entity => entity.GetTableName() == table.Name && entity.GetSchema() == table.Schema);
                var mapped = entity?.GetProperties().Select(property => property.GetColumnName(StoreObjectIdentifier.Table(table.Name, table.Schema))).ToHashSet(StringComparer.Ordinal) ?? [];
                foreach (var column in table.Columns.Where(column => !mapped.Contains(column.Name)))
                {
                    Console.Error.WriteLine($"Unmapped: {table.Schema}.{table.Name}.{column.Name} ({column.StoreType})");
                }
            }

            throw new InvalidOperationException($"Scaffolding metadata mismatch: {scaffolded.AdditionalFiles.Count}/{schema.Tables.Count} tables, " +
                $"{model.GetEntityTypes().Sum(entity => entity.GetProperties().Count())}/{schema.Tables.Sum(table => table.Columns.Count)} columns, " +
                $"{model.GetEntityTypes().Sum(entity => entity.GetForeignKeys().Count())}/{schema.Tables.Sum(table => table.ForeignKeys.Count)} foreign keys.");
        }

        var files = scaffolded.AdditionalFiles.Prepend(scaffolded.ContextFile).ToDictionary(
            file => Path.Combine(root, "Model/Generated", file.Path),
            file => "// <auto-generated/>\n// Source: pinned Microsoft AdventureWorks OLTP install script.\n#nullable enable\n" + file.Code,
            StringComparer.Ordinal);
        files.Add(Path.Combine(root, "Model/schema.json"), JsonSerializer.Serialize(new
        {
            source = "sql-server-samples/samples/databases/adventure-works/oltp-install-script/instawdb.sql",
            sha256 = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(File.ReadAllText(source).ReplaceLineEndings("\n")))).ToLowerInvariant(),
            tables = schema.Tables.Count,
            columns = schema.Tables.Sum(table => table.Columns.Count),
            primaryKeys = schema.Tables.Count(table => table.PrimaryKey is not null),
            foreignKeys = schema.Tables.Sum(table => table.ForeignKeys.Count),
            indexes = schema.Tables.Sum(table => table.Indexes.Count),
            computedColumns = schema.Tables.Sum(table => table.Columns.Count(column => column.ComputedColumnSql is not null))
        }, JsonOptions) + "\n");
        var stale = false;
        foreach (var (path, content) in files)
        {
            var normalized = content.ReplaceLineEndings("\n");
            if (args.Length == 2)
            {
                if (!File.Exists(path) || File.ReadAllText(path).ReplaceLineEndings("\n") != normalized)
                {
                    Console.Error.WriteLine("Stale model: " + Path.GetRelativePath(root, path));
                    stale = true;
                }
            }
            else
            {
                Directory.CreateDirectory(Path.GetDirectoryName(path)!);
                File.WriteAllText(path, normalized);
            }
        }

        Console.WriteLine($"AdventureWorks model: {schema.Tables.Count} tables, {schema.Tables.Sum(table => table.ForeignKeys.Count)} foreign keys; {(args.Length == 2 ? "checked" : "scaffolded")} without a database.");
        return stale ? 3 : 0;
    }
}
