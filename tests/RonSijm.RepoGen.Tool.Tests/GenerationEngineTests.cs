using FluentAssertions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.EntityFrameworkCore;
using Xunit;

namespace RonSijm.RepoGen.Tool.Tests;

public sealed class GenerationEngineTests
{
    [Theory]
    [InlineData(RepositoryOutputLayout.SingleFile)]
    [InlineData(RepositoryOutputLayout.PerEntity)]
    [InlineData(RepositoryOutputLayout.PerContract)]
    public void CodeFirstGenerationCompilesAndIsDeterministic(RepositoryOutputLayout layout)
    {
        using var context = new ClosedContext(new DbContextOptionsBuilder<ClosedContext>().UseSqlite("Data Source=:memory:").Options);
        var first = RepositoryGenerator.Generate(context, new ValidationFixtureDesigner(), layout);
        var second = RepositoryGenerator.Generate(context, new ValidationFixtureDesigner(), layout);
        first.Files.Should().Equal(second.Files);
        var paths = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator).Append(typeof(ClosedContext).Assembly.Location);
        var compilation = CSharpCompilation.Create("CodeFirst_" + Guid.NewGuid().ToString("N"), first.Files.Where(static file => file.Kind != RepositoryOutputKind.Manifest).Select(static file => CSharpSyntaxTree.ParseText(file.Contents)),
            paths.Distinct(StringComparer.OrdinalIgnoreCase).Select(static path => MetadataReference.CreateFromFile(path)), new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        using var assembly = new MemoryStream();
        compilation.Emit(assembly).Diagnostics.Where(static diagnostic => diagnostic.Severity == DiagnosticSeverity.Error).Should().BeEmpty();
    }

    [Fact]
    public void SplitChecksReportObsoleteOwnedFilesWithoutDeletingThem()
    {
        using var context = new ClosedContext(new DbContextOptionsBuilder<ClosedContext>().UseSqlite("Data Source=:memory:").Options);
        var bundle = RepositoryGenerator.Generate(context, new ValidationFixtureDesigner(), RepositoryOutputLayout.PerEntity);
        var directory = Path.Combine(Path.GetTempPath(), "repogen-split-" + Guid.NewGuid().ToString("N"));
        var locations = new RepositoryOutputLocations(Path.Combine(directory, "persistence"), Path.Combine(directory, "contracts"), Manifest: Path.Combine(directory, "manifest.json"));
        try
        {
            bundle.Write(locations);
            var obsolete = Path.Combine(locations.Repositories, "Old.g.cs");
            File.WriteAllText(obsolete, bundle.Files.First(static file => file.Kind == RepositoryOutputKind.Repositories).Contents);
            bundle.Check(locations).Should().ContainSingle().Which.DiagnosticId.Should().Be("RGG0004");
            bundle.Write(locations).Should().BeEmpty();
            File.Exists(obsolete).Should().BeTrue();
        }
        finally
        {
            if (Directory.Exists(directory))
            {
                Directory.Delete(directory, recursive: true);
            }
        }
    }

    [Fact]
    public void CheckDoesNotCreateFilesAndAllPathsArePreflightedBeforeAnyWrite()
    {
        using var context = new ClosedContext(new DbContextOptionsBuilder<ClosedContext>().UseSqlite("Data Source=:memory:").Options);
        var bundle = RepositoryGenerator.Generate(context, new ValidationFixtureDesigner());
        var directory = Path.Combine(Path.GetTempPath(), "repogen-engine-" + Guid.NewGuid().ToString("N"));
        var locations = new RepositoryOutputLocations(Path.Combine(directory, "repos.g.cs"), Path.Combine(directory, "contracts.g.cs"), Manifest: Path.Combine(directory, "manifest.json"));
        bundle.Check(locations).Should().HaveCount(3);
        Directory.Exists(directory).Should().BeFalse();
        Directory.CreateDirectory(directory);
        try
        {
            File.WriteAllText(locations.Contracts!, "// Handwritten application code");
            Action write = () => bundle.Write(locations);
            write.Should().Throw<InvalidOperationException>().WithMessage("*RGG0003*handwritten*");
            File.Exists(locations.Repositories).Should().BeFalse();
            File.Exists(locations.Manifest).Should().BeFalse();
            File.ReadAllText(locations.Contracts!).Should().Be("// Handwritten application code");
            File.Delete(locations.Contracts!);
            bundle.Write(locations).Should().HaveCount(3);
            bundle.Check(locations).Should().BeEmpty();
            bundle.Write(locations).Should().BeEmpty();
            File.WriteAllText(locations.Repositories, "// <auto-generated/>\n// Old generator output");
            bundle.Check(locations).Should().ContainSingle();
            bundle.Write(locations).Should().ContainSingle();
        }
        finally { Directory.Delete(directory, recursive: true); }
    }
}